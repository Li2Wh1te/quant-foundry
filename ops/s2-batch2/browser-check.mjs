  await page.getByRole('link',{name:'查看 K 线',exact:true}).click();
  await page.getByText('512 / 10,000 根',{exact:false}).waitFor();
  await page.locator('.qfe-chart canvas').first().waitFor();
  assert.equal(await page.locator('.qfe-chart-empty').count(),0);
  assert.equal(await page.locator('#qfb-price-basis option[value="pre"]').isDisabled(),true);
  assert.equal(await page.locator('#qfb-price-basis option[value="post"]').isDisabled(),true);
  findings.push('real image summary → paged/searchable directory → keyboard calendar → profile → raw chart; production pre/post visibly restricted');
  await page.getByRole('button',{name:'加载更早历史',exact:true}).click();
  await page.waitForFunction(() => !document.querySelector('.qfe-history-actions')?.textContent.includes('512 / 10,000'));
