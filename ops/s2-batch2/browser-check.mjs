  await page.getByRole('button',{name:'精确值表',exact:true}).click();
  assert.ok((await page.locator('.qfe-exact-values').innerText()).includes('9007199254740993.1234'));
  await page.getByRole('button',{name:'精确值表',exact:true}).click();
